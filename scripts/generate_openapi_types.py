"""Generate TypeScript types from FastAPI OpenAPI schema.

Reads OpenAPI schema from FastAPI `app` in api.py and generates clean,
strongly-typed TypeScript interfaces in ui/src/types/api.ts.
"""

import json
import sys
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT_DIR))

from api import app

OUTPUT_FILE = Path(__file__).resolve().parent.parent / "ui" / "src" / "types" / "api.ts"
OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)

def openapi_type_to_ts(prop: dict, required: bool = True) -> str:
    """Map OpenAPI schema property to TypeScript type string."""
    if "$ref" in prop:
        ref_name = prop["$ref"].split("/")[-1]
        return ref_name

    if "anyOf" in prop:
        types = [openapi_type_to_ts(p) for p in prop["anyOf"] if p.get("type") != "null"]
        if any(p.get("type") == "null" for p in prop["anyOf"]):
            types.append("null")
        return " | ".join(types) if types else "any"

    p_type = prop.get("type")
    if p_type == "string":
        if "enum" in prop:
            return " | ".join([f'"{val}"' for val in prop["enum"]])
        return "string"
    elif p_type in ("integer", "number"):
        return "number"
    elif p_type == "boolean":
        return "boolean"
    elif p_type == "array":
        item_schema = prop.get("items", {})
        item_type = openapi_type_to_ts(item_schema)
        if " " in item_type or "|" in item_type:
            return f"({item_type})[]"
        return f"{item_type}[]"
    elif p_type == "object":
        add_props = prop.get("additionalProperties")
        if isinstance(add_props, dict):
            val_type = openapi_type_to_ts(add_props)
            return f"Record<string, {val_type}>"
        return "Record<string, any>"
    
    return "any"

def generate_typescript_definitions():
    """Extract schema from FastAPI and emit TypeScript interfaces."""
    spec = app.openapi()
    schemas = spec.get("components", {}).get("schemas", {})

    lines = [
        "/**",
        " * Auto-generated TypeScript types from FastAPI OpenAPI Schema.",
        " * Generated by scripts/generate_openapi_types.py.",
        " * DO NOT EDIT MANUALLY - Run `python scripts/generate_openapi_types.py` to regenerate.",
        " */",
        "",
        "/** Standardized error envelope returned for all API exceptions */",
        "export interface ErrorResponse {",
        "  error: string;",
        "  message: string;",
        "  detail?: any;",
        "}",
        "",
    ]

    for name, schema in sorted(schemas.items()):
        description = schema.get("description", "")
        if description:
            lines.append("/**")
            lines.append(f" * {description}")
            lines.append(" */")

        # Handle Enums
        if "enum" in schema:
            enum_values = " | ".join([f'"{val}"' for val in schema["enum"]])
            lines.append(f"export type {name} = {enum_values};")
            lines.append("")
            continue

        # Handle Object Schemas
        properties = schema.get("properties", {})
        required_fields = set(schema.get("required", []))

        lines.append(f"export interface {name} {{")
        for prop_name, prop_schema in properties.items():
            prop_desc = prop_schema.get("description", "")
            if prop_desc:
                lines.append(f"  /** {prop_desc} */")
            
            is_req = prop_name in required_fields
            optional_marker = "" if is_req else "?"
            ts_type = openapi_type_to_ts(prop_schema)
            lines.append(f"  {prop_name}{optional_marker}: {ts_type};")
        lines.append("}")
        lines.append("")

    content = "\n".join(lines)
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write(content)

    print(f"Successfully generated TypeScript definitions ({len(schemas)} schemas) at: {OUTPUT_FILE}")

if __name__ == "__main__":
    generate_typescript_definitions()
